def deserialize_chat_messages(chat_messages):
    """
    Deserializes the chat messages from a defaultdict and converts it into a JSON-serializable format.
    """
    serialized_messages = []
    
    for agent, messages in chat_messages.items():
        # Convert the agent object to a string or extract relevant attributes if needed
        agent_name = str(agent)  # You can customize this if the agent has a specific attribute like `agent.name`
        
        for message in messages:
            # Ensure each message is JSON-serializable
            serialized_message = {
                "agent": agent_name,
                "content": message.get("content"),
                "role": message.get("role"),
                "name": message.get("name")
            }
            serialized_messages.append(serialized_message)
    
    return serialized_messages


